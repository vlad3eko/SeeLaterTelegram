export const createInstagramHook = (
    mediaType: string,
    contentType: ContentType
): string => {
    if (!mediaType || !contentType) {
        return ''
    }

    const hooks = HOOK_TEMPLATES[contentType]

    if (!hooks?.length) {
        return ''
    }

    const randomIndex = Math.floor(Math.random() * hooks.length)

    return hooks[randomIndex] ?? ''
}
