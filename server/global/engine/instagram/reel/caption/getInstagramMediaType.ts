export const createInstagramHook = (
    mediaType: string,
    contentType: ContentType
) => {
    const type =
        contentTypeConvert(
            mediaType,
            contentType
        )

    if (!type) {
        return ''
    }

    const hooks =
        HOOK_TEMPLATES[type]

    if (!hooks?.length) {
        return ''
    }

    return hooks[
        Math.floor(
            Math.random() * hooks.length
        )
        ]!
}
