-- Очередь автопубликации трейлеров с YouTube-каналов (server/global/engine/youtube/).
--
-- Таймер (/api/bot/youtubeQueue/tick в production, dev-плагин локально) делает два шага:
--   1. Новые ролики отслеживаемых каналов с «дубляж» в названии попадают сюда со статусом queued.
--   2. Не чаще раза в интервал (по умолчанию 2 часа) claim_youtube_queue_item выдаёт самый
--      старый queued; бот находит фильм в TMDB и ставит обычную задачу Reel (dispatchReelJob,
--      без проверки) — дальше воркер и финализатор, как при кнопке «Опубликовать».
--      Как только задача поставлена, строка из очереди УДАЛЯЕТСЯ: ролик живёт дальше
--      в reel_processing_jobs. Повторно в очередь он не попадёт: проверка канала пропускает
--      ролики, чей ключ уже есть в reel_processing_jobs или published_media_messages.
--
-- Приоритет: ролики каналов с priority в config.ts (KinomanTrailers, русский дубляж) выдаются
-- раньше остальных (p_priority_channels).
--
-- Статусы:
--   skipped      — ролик был на канале до начала слежения или в названии нет ключевого слова;
--   queued       — ждёт своей очереди;
--   dispatching  — выдан таймеру, идёт поиск фильма и постановка задачи (несколько секунд);
--   failed       — фильм не найден в TMDB и т. п. (last_error); остаётся, чтобы не ставиться снова.
--   (dispatched и published остались от первой версии и больше не используются.)
--
-- Выполнить в Supabase SQL Editor до первого запуска таймера. Повторный запуск безопасен
-- (обновляет функцию claim_youtube_queue_item).

begin;

create table if not exists public.youtube_publish_queue (
    id bigint generated by default as identity primary key,
    channel_id text not null,
    video_id text not null unique,
    title text not null,
    video_published_at timestamptz,

    status text not null default 'queued',
    attempts integer not null default 0,
    not_before timestamptz,
    last_error text,

    media_id bigint,
    media_type text,
    content_type text,
    tmdb_title text,
    reel_job_id uuid,

    dispatched_at timestamptz,
    finished_at timestamptz,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),

    constraint youtube_publish_queue_status_check
        check (status in ('skipped', 'queued', 'dispatching', 'dispatched', 'published', 'failed'))
);

create index if not exists youtube_publish_queue_pending
    on public.youtube_publish_queue (status, video_published_at, id)
    where status in ('queued', 'dispatching', 'dispatched');

create index if not exists youtube_publish_queue_channel
    on public.youtube_publish_queue (channel_id);

